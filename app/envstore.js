'use strict';
// Runtime API key / env var manager, global & repo agent instructions editor, and MCP server config manager.
const fs = require('fs');
const path = require('path');

const HOME = process.env.HOME || '/home/dev';
const HUB_DIR = path.join(HOME, '.agent-hub');
const ENV_JSON = path.join(HUB_DIR, 'env.json');
const ENV_SH = path.join(HUB_DIR, 'env.sh');
const KEY_RE = /^[A-Z_][A-Z0-9_]{1,63}$/;
const MASK = '••••';

const KNOWN_KEYS = [
  { key: 'ANTHROPIC_API_KEY', label: 'Anthropic API key', hint: 'Claude Code, OpenCode, Pi' },
  { key: 'OPENAI_API_KEY',    label: 'OpenAI API key',    hint: 'Codex, OpenCode, Pi, Qwen Code' },
  { key: 'OPENAI_BASE_URL',   label: 'OpenAI Base URL',   hint: 'Optional OpenAI-compatible gateway' },
  { key: 'GEMINI_API_KEY',    label: 'Gemini API key',    hint: 'Gemini CLI' },
  { key: 'DEEPSEEK_API_KEY',  label: 'DeepSeek API key',  hint: 'DeepSeek Harness (dsh)' },
  { key: 'DEEPSEEK_BASE_URL', label: 'DeepSeek Base URL', hint: 'Optional custom DeepSeek endpoint' },
  { key: 'DASHSCOPE_API_KEY', label: 'DashScope API key', hint: 'Qwen Code (Alibaba Cloud)' },
  { key: 'OPENROUTER_API_KEY', label: 'OpenRouter API key', hint: 'OpenCode, Pi, OpenAI-compatible' },
];

const INSTRUCTION_NAMES = ['CLAUDE.md', 'AGENTS.md', 'GEMINI.md'];

const MCP_TARGETS = {
  claude:   { label: 'Claude Code', file: () => path.join(HOME, '.claude.json'), prop: 'mcpServers' },
  gemini:   { label: 'Gemini CLI',  file: () => path.join(HOME, '.gemini', 'settings.json'), prop: 'mcpServers' },
  opencode: { label: 'OpenCode',    file: () => path.join(HOME, '.config', 'opencode', 'opencode.json'), prop: 'mcp' },
};

function readJson(file, fallback) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); }
  catch (e) {
    if (e.code === 'ENOENT') return fallback;
    throw new Error(`${file} is not valid JSON (${e.message})`);
  }
}

function writeAtomic(file, text, mode, backup = false) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (backup && fs.existsSync(file)) fs.copyFileSync(file, file + '.bak');
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text, mode ? { mode } : undefined);
  fs.renameSync(tmp, file);
}

function loadSavedEnv() {
  try {
    const d = JSON.parse(fs.readFileSync(ENV_JSON, 'utf8'));
    if (d && typeof d === 'object' && !Array.isArray(d)) {
      const out = {};
      for (const [k, v] of Object.entries(d)) {
        if (KEY_RE.test(k) && typeof v === 'string' && v.length) out[k] = v;
      }
      return out;
    }
  } catch {}
  return {};
}

function shellQuote(v) {
  return `'${String(v).replace(/'/g, `'\\''`)}'`;
}

function syncEnvShell(vars) {
  const lines = ['# Generated by Agent Hub (System → API Keys)'];
  for (const [k, v] of Object.entries(vars)) {
    if (KEY_RE.test(k) && v) lines.push(`export ${k}=${shellQuote(v)}`);
  }
  writeAtomic(ENV_SH, lines.join('\n') + '\n', 0o600);
}

function saveEnvVars(patch) {
  const cur = loadSavedEnv();
  for (const [rawKey, rawVal] of Object.entries(patch || {})) {
    const key = String(rawKey || '').trim().toUpperCase();
    if (!KEY_RE.test(key)) throw new Error(`Invalid env var name "${rawKey}" (use A-Z, 0-9, _)`);
    if (rawVal === null || rawVal === '') {
      delete cur[key];
    } else if (typeof rawVal === 'string' && rawVal !== MASK) {
      if (rawVal.length > 8192) throw new Error(`${key}: value too long`);
      if (/[\r\n\0]/.test(rawVal)) throw new Error(`${key}: value cannot contain newlines`);
      cur[key] = rawVal;
    }
  }
  writeAtomic(ENV_JSON, JSON.stringify(cur, null, 2) + '\n', 0o600);
  syncEnvShell(cur);
  return cur;
}

function getEnvOverrides() {
  return loadSavedEnv();
}

function maskValue(v) {
  if (!v) return '';
  if (v.length <= 8) return MASK;
  return `${v.slice(0, 4)}••••${v.slice(-4)}`;
}

function resolveInstructionPath(scope, name, repo, repoDir) {
  if (scope === 'global') {
    const map = {
      'CLAUDE.md': path.join(HOME, '.claude', 'CLAUDE.md'),
      'AGENTS.md': path.join(HOME, '.codex', 'AGENTS.md'),
      'GEMINI.md': path.join(HOME, '.gemini', 'GEMINI.md'),
    };
    if (!map[name]) throw new Error('Unknown global instruction file');
    return map[name];
  }
  if (!INSTRUCTION_NAMES.includes(name)) throw new Error('Allowed files: ' + INSTRUCTION_NAMES.join(', '));
  const dir = repoDir(repo);
  if (!fs.existsSync(dir)) throw new Error('repo not found');
  return path.join(dir, name);
}

function register(app, wrap, helpers) {
  // Ensure env.sh exists on startup if env.json already exists
  const initial = loadSavedEnv();
  if (Object.keys(initial).length) {
    try { syncEnvShell(initial); } catch {}
  }

  app.get('/api/env', wrap(async (req, res) => {
    const saved = loadSavedEnv();
    const keys = new Set([...KNOWN_KEYS.map((k) => k.key), ...Object.keys(saved)]);
    const knownMap = Object.fromEntries(KNOWN_KEYS.map((k) => [k.key, k]));
    const vars = [...keys].map((key) => {
      const savedVal = saved[key] || '';
      const envVal = process.env[key] || '';
      const effective = savedVal || envVal;
      return {
        key,
        label: knownMap[key]?.label || key,
        hint: knownMap[key]?.hint || 'Custom variable',
        custom: !knownMap[key],
        saved: !!savedVal,
        fromEnv: !!envVal && !savedVal,
        masked: maskValue(effective),
      };
    });
    res.json({ vars });
  }));

  app.post('/api/env', wrap(async (req, res) => {
    if (!req.body?.vars || typeof req.body.vars !== 'object') throw new Error('vars object required');
    saveEnvVars(req.body.vars);
    res.json({ ok: true });
  }));

  app.delete('/api/env/:key', wrap(async (req, res) => {
    const key = String(req.params.key || '').toUpperCase();
    if (!KEY_RE.test(key)) throw new Error('invalid key');
    saveEnvVars({ [key]: '' });
    res.json({ ok: true });
  }));

  // ---- Agent Instructions (CLAUDE.md / AGENTS.md / GEMINI.md) ----
  app.get('/api/config/instructions', wrap(async (req, res) => {
    const scope = req.query.scope === 'repo' ? 'repo' : 'global';
    const repo = String(req.query.repo || '');
    const files = INSTRUCTION_NAMES.map((name) => {
      const p = resolveInstructionPath(scope, name, repo, helpers.repoDir);
      let content = '';
      let exists = false;
      try { content = fs.readFileSync(p, 'utf8'); exists = true; } catch {}
      return { name, path: p, exists, content };
    });
    res.json({ scope, repo, files });
  }));

  app.put('/api/config/instructions', wrap(async (req, res) => {
    const scope = req.body?.scope === 'repo' ? 'repo' : 'global';
    const repo = String(req.body?.repo || '');
    const name = String(req.body?.name || '');
    const content = String(req.body?.content ?? '');
    if (Buffer.byteLength(content, 'utf8') > 256 * 1024) throw new Error('File too large (max 256 KB)');
    const p = resolveInstructionPath(scope, name, repo, helpers.repoDir);
    writeAtomic(p, content, undefined, true);
    res.json({ ok: true, path: p });
  }));

  // ---- MCP Server Configs ----
  app.get('/api/config/mcp', wrap(async (req, res) => {
    const targets = {};
    for (const [k, t] of Object.entries(MCP_TARGETS)) {
      const file = t.file();
      let servers = {};
      let error = '';
      try {
        const cfg = readJson(file, {});
        servers = (cfg && typeof cfg[t.prop] === 'object' && cfg[t.prop]) || {};
      } catch (e) { error = e.message; }
      targets[k] = { key: k, label: t.label, file, prop: t.prop, servers, error };
    }
    res.json({ targets });
  }));

  app.put('/api/config/mcp', wrap(async (req, res) => {
    const targetKey = String(req.body?.target || '');
    const t = MCP_TARGETS[targetKey];
    if (!t) throw new Error('unknown MCP target');
    const servers = req.body?.servers;
    if (!servers || typeof servers !== 'object' || Array.isArray(servers)) {
      throw new Error('servers must be a JSON object mapping server names to configs');
    }
    const file = t.file();
    const cfg = readJson(file, {});
    cfg[t.prop] = servers;
    writeAtomic(file, JSON.stringify(cfg, null, 2) + '\n', undefined, true);
    res.json({ ok: true, file });
  }));
}

module.exports = { register, getEnvOverrides, saveEnvVars, loadSavedEnv, maskValue, ENV_SH };
